#!/usr/bin/env python3
"""Synthetic logs for the scalability measurements (Sect. "Scalability" of the paper).

Each of n data subjects s0..s(n-1) contributes two events, GiveConsent and StartProcessing
(data "d"), so a log has 2n events and every processing has a legal basis (compliant log:
TLC must explore the whole state space).

  seq   all 2n events have pairwise distinct timestamps (minute 2i and 2i+1)
  ties  all n consents share one minute and all n processing starts the next minute,
        i.e. two groups of n simultaneous events (worst case for interleavings)

Generate a module only:
  python3 gen_scale.py 10 seq                 # writes MC_Scale.tla (20 events)
  python3 gen_scale.py 10 ties -o -           # print to stdout

Generate and run TLC for several sizes, print a results table:
  python3 gen_scale.py --sweep 5,10,20,40 --mode seq --jar ../tla_modules/tla2tools.jar
"""
import argparse
import re
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAX_MINUTE = 24 * 60 - 1


def module(n: int, ties: bool) -> str:
    if n < 1:
        sys.exit("n must be >= 1")
    if not ties and 2 * n - 1 > MAX_MINUTE:
        sys.exit(f"seq mode supports at most {MAX_MINUTE // 2 + 1} subjects (one day of minutes)")
    subs = [f"s{i}" for i in range(n)]
    ev = []
    for i, s in enumerate(subs):
        t1, t2 = (0, 1) if ties else (2 * i, 2 * i + 1)
        ev.append(f'[type|->"GiveConsent", time|->M({t1}), subject|->"{s}", data|->"d"]')
        ev.append(f'[type|->"StartProcessing", time|->M({t2}), subject|->"{s}", data|->"d"]')
    return ("---- MODULE MC_Scale ----\n"
            f"\\* generated by gen_scale.py: n={n}, mode={'ties' if ties else 'seq'}, {2 * n} events\n"
            "EXTENDS MC_GDPR_Time\n"
            "M(k) == [year|->2025, month|->7, day|->12, hour|->(k \\div 60), minute|->(k % 60)]\n"
            "ScaleSubjects == {" + ",".join(f'"{s}"' for s in subs) + "}\n"
            "ScaleEvents == {" + ",\n ".join(ev) + "}\n====\n")


def run_tlc(jar: Path, workers: int, timeout: int):
    t0 = time.time()
    try:
        res = subprocess.run(["java", "-cp", str(jar), "tlc2.TLC", "-workers", str(workers),
                              "-metadir", str(HERE / "states_scale"), "MC_Scale.tla",
                              "-config", "MC_Scale.cfg"],
                             cwd=HERE, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None, None, f">{timeout}s (timeout)"
    wall = time.time() - t0
    out = res.stdout
    m = re.search(r"([\d,]+) distinct states found, 0 states left", out)
    if not m:
        sys.exit(f"TLC did not complete (exit {res.returncode}):\n{out[-1500:]}\n{res.stderr[-1500:]}")
    verdict = "violated" if "is violated" in out else "holds"
    return int(m.group(1).replace(",", "")), verdict, f"{wall:.1f}s"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("n", nargs="?", type=int, default=10, help="number of data subjects (events = 2n); default 10")
    ap.add_argument("mode", nargs="?", choices=["seq", "ties"], default=None, help="default seq")
    ap.add_argument("--mode", dest="mode_opt", choices=["seq", "ties"], help="same as positional mode")
    ap.add_argument("-o", default=str(HERE / "MC_Scale.tla"), help="output module ('-' = stdout)")
    ap.add_argument("--sweep", help="comma-separated list of n; generates and runs TLC for each")
    ap.add_argument("--jar", help="path to tla2tools.jar (required with --sweep)")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--timeout", type=int, default=600, help="seconds per TLC run")
    a = ap.parse_args()
    ties = (a.mode_opt or a.mode or "seq") == "ties"

    if not a.sweep:
        text = module(a.n, ties)
        if a.o == "-":
            sys.stdout.write(text)
        else:
            Path(a.o).write_text(text)
            print(f"wrote {a.o} ({2 * a.n} events, mode={'ties' if ties else 'seq'})", file=sys.stderr)
        return

    if not a.jar:
        sys.exit("--sweep needs --jar /path/to/tla2tools.jar")
    jar = Path(a.jar).expanduser().resolve()
    if not jar.is_file():
        sys.exit(f"tla2tools.jar not found: {jar}")
    if not (HERE / "MC_Scale.cfg").is_file():
        sys.exit(f"MC_Scale.cfg not found next to {Path(__file__).name}")
    print(f"mode={'ties' if ties else 'seq'}, workers={a.workers}")
    print(f"{'subjects':>8} {'events':>7} {'distinct states':>16} {'verdict':>9} {'wall':>12}")
    for n in [int(x) for x in a.sweep.split(",")]:
        (HERE / "MC_Scale.tla").write_text(module(n, ties))
        states, verdict, wall = run_tlc(jar, a.workers, a.timeout)
        print(f"{n:>8} {2 * n:>7} {states if states is not None else '-':>16} {verdict or '-':>9} {wall:>12}",
              flush=True)


if __name__ == "__main__":
    main()
