#!/usr/bin/env python3
"""Synthetic logs for the scalability measurements (Sect. "Scalability" of the paper).

In modes seq and ties, each of n data subjects s0..s(n-1) contributes two events, GiveConsent
and StartProcessing (data "d"), so a log has 2n events and every processing has a legal basis
(compliant log: TLC must explore the whole state space).

  seq   all 2n events have pairwise distinct timestamps (minute 2i and 2i+1)
  ties  all n consents share one minute and all n processing starts the next minute,
        i.e. two groups of n simultaneous events (worst case for interleavings)
  unlawful  n processing events without any legal basis, distinct timestamps (n events);
        checked against NoRejectedEvents only, which holds, so TLC must explore everything

Generate a module only (MC_Scale.cfg is written alongside):
  python3 gen_scale.py 10 seq                 # writes MC_Scale.tla (20 events)
  python3 gen_scale.py 10 ties -o -           # print to stdout

Write the same log as JSON (input for tools/check_log.py, e.g. to compare projection):
  python3 gen_scale.py 12 ties --json ties12.json

Generate and run TLC for several sizes, print a results table:
  python3 gen_scale.py --sweep 5,10,20,40 --mode seq --jar ../tla_modules/tla2tools.jar
  python3 gen_scale.py --sweep 5,10,20,40 --mode unlawful --jar ../tla_modules/tla2tools.jar
"""
import argparse
import re
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAX_MINUTE = 24 * 60 - 1


def log_events(n: int, mode: str) -> list[tuple[str, int, str]]:
    """(type, minute, subject) triples."""
    if mode == "unlawful":
        return [("StartProcessing", i, f"s{i}") for i in range(n)]
    out = []
    for i in range(n):
        t1, t2 = (0, 1) if mode == "ties" else (2 * i, 2 * i + 1)
        out += [("GiveConsent", t1, f"s{i}"), ("StartProcessing", t2, f"s{i}")]
    return out


DEFAULT_INVARIANTS = {"seq": "AllProcessingIsLawful,NoRejectedEvents",
                      "ties": "AllProcessingIsLawful,NoRejectedEvents",
                      "unlawful": "NoRejectedEvents"}


def config(invariants: str) -> str:
    return ("SPECIFICATION Spec\nCONSTANTS\n"
            "    DataSubjects <- ScaleSubjects\n    Data = {\"d\"}\n    ObservedEvents <- ScaleEvents\n"
            "    YearRange <- MC_YearRange\n    MonthRange <- MC_MonthRange\n    DayRange <- MC_DayRange\n"
            "    HourRange <- MC_HourRange\n    MinuteRange <- MC_MinuteRange\n"
            "    FixedEndTime <- MC_MAX_TIME\n"
            + "".join(f"INVARIANT {i}\n" for i in invariants.split(",") if i))


def module(n: int, mode: str) -> str:
    if n < 1:
        sys.exit("n must be >= 1")
    evs = log_events(n, mode)
    if max(m for _, m, _ in evs) > MAX_MINUTE:
        sys.exit(f"mode {mode}: n={n} does not fit into one day of minutes")
    subs = sorted({s for _, _, s in evs}, key=lambda x: int(x[1:]))
    ev = [f'[type|->"{t}", time|->M({m}), subject|->"{s}", data|->"d"]' for t, m, s in evs]
    return ("---- MODULE MC_Scale ----\n"
            f"\\* generated by gen_scale.py: n={n}, mode={mode}, {len(evs)} events\n"
            "EXTENDS MC_GDPR_Time\n"
            "M(k) == [year|->2025, month|->7, day|->12, hour|->(k \\div 60), minute|->(k % 60)]\n"
            "ScaleSubjects == {" + ",".join(f'"{s}"' for s in subs) + "}\n"
            "ScaleEvents == {" + ",\n ".join(ev) + "}\n====\n")


def json_log(n: int, mode: str) -> list[dict]:
    return [{"type": t, "time": f"2025-07-12 {m // 60:02d}:{m % 60:02d}", "subject": s, "data": "d"}
            for t, m, s in log_events(n, mode)]


def run_tlc(jar: Path, workers: int, timeout: int):
    t0 = time.time()
    try:
        res = subprocess.run(["java", "-cp", str(jar), "tlc2.TLC", "-noGenerateSpecTE", "-workers", str(workers),
                              "-metadir", str(HERE / "states_scale"), "MC_Scale.tla",
                              "-config", "MC_Scale.cfg"],
                             cwd=HERE, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None, None, f">{timeout}s (timeout)"
    wall = time.time() - t0
    out = res.stdout
    # final summary only; Progress(...) lines also report distinct states
    m = re.findall(r"([\d,]+) distinct states found, [\d,]+ states left on queue", out)
    if "is violated" in out:
        verdict = "violated"
    elif "No error has been found" in out:
        verdict = "holds"
    else:
        sys.exit(f"TLC did not complete (exit {res.returncode}):\n{out[-1500:]}\n{res.stderr[-1500:]}")
    return (int(m[-1].replace(",", "")) if m else None), verdict, f"{wall:.1f}s"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    modes = ["seq", "ties", "unlawful"]
    ap.add_argument("n", nargs="?", type=int, default=10, help="number of data subjects; default 10")
    ap.add_argument("mode", nargs="?", choices=modes, default=None, help="default seq")
    ap.add_argument("--mode", dest="mode_opt", choices=modes, help="same as positional mode")
    ap.add_argument("-o", default=str(HERE / "MC_Scale.tla"), help="output module ('-' = stdout)")
    ap.add_argument("--json", type=Path, help="also write the log as JSON for tools/check_log.py")
    ap.add_argument("--sweep", help="comma-separated list of n; generates and runs TLC for each")
    ap.add_argument("--jar", help="path to tla2tools.jar (required with --sweep)")
    ap.add_argument("--invariants", help="invariants checked by --sweep (default depends on mode: "
                    + "; ".join(f"{k}: {v}" for k, v in DEFAULT_INVARIANTS.items()) + ")")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--timeout", type=int, default=600, help="seconds per TLC run")
    a = ap.parse_args()
    mode = a.mode_opt or a.mode or "seq"
    invariants = a.invariants or DEFAULT_INVARIANTS[mode]

    if a.json:
        import json
        a.json.write_text(json.dumps(json_log(a.n, mode), indent=1))
        print(f"wrote {a.json}", file=sys.stderr)
    if not a.sweep:
        text = module(a.n, mode)
        if a.o == "-":
            sys.stdout.write(text)
        else:
            Path(a.o).write_text(text)
            (Path(a.o).parent / "MC_Scale.cfg").write_text(config(invariants))
            print(f"wrote {a.o} and MC_Scale.cfg ({len(log_events(a.n, mode))} events, mode={mode})",
                  file=sys.stderr)
        return

    if not a.jar:
        sys.exit("--sweep needs --jar /path/to/tla2tools.jar")
    jar = Path(a.jar).expanduser().resolve()
    if not jar.is_file():
        sys.exit(f"tla2tools.jar not found: {jar}")
    (HERE / "MC_Scale.cfg").write_text(config(invariants))
    print(f"mode={mode}, invariants={invariants}, workers={a.workers}")
    print(f"{'subjects':>8} {'events':>7} {'distinct states':>16} {'verdict':>9} {'wall':>12}")
    for n in [int(x) for x in a.sweep.split(",")]:
        (HERE / "MC_Scale.tla").write_text(module(n, mode))
        states, verdict, wall = run_tlc(jar, a.workers, a.timeout)
        print(f"{n:>8} {len(log_events(n, mode)):>7} {states if states is not None else '-':>16} "
              f"{verdict or '-':>9} {wall:>12}", flush=True)


if __name__ == "__main__":
    main()
